"""Prueba de extras/boot/limine-theme.py: cambia solo el aspecto y deja las entradas idénticas.
Uso: python3 -I tests/limine_theme_test.py"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("lt", os.path.join(HERE, "..", "extras", "boot", "limine-theme.py"))
lt = importlib.util.module_from_spec(spec)
spec.loader.exec_module(lt)

# Parte de la configuración real de la persona (con CachyOS, instantáneas, Windows y el cargador de respaldo)
SAMPLE = """timeout: 5
default_entry: 2
remember_last_entry: yes

# CachyOS Limine theme
# Author: diegons490 (https://github.com/diegons490/cachyos-limine-theme)
term_palette: 1e1e2e;f38ba8;a6e3a1;f9e2af;89b4fa;f5c2e7;94e2d5;cdd6f4
term_palette_bright: 585b70;f38ba8;a6e3a1;f9e2af;89b4fa;f5c2e7;94e2d5;cdd6f4
term_background: ffffffff
term_foreground: cdd6f4
term_background_bright: ffffffff
term_foreground_bright: cdd6f4
interface_branding:
wallpaper: boot():/limine-splash.png

comment: machine-id=591005bdc59a48039ad30cf7fa7c6959
/+CachyOS
  //linux-cachyos
  ### This kernel entry is auto-generated by limine-entry-tool
  comment: Kernel version: 7.2.9-2-cachyos
  protocol: linux
  module_path: boot():/591005bdc59a48039ad30cf7fa7c6959/linux-cachyos/initramfs#4d0314685d13bf05
  path: boot():/591005bdc59a48039ad30cf7fa7c6959/linux-cachyos/vmlinuz#27b15b0314621c465c994e88da7b149f
  cmdline: quiet nowatchdog splash rw video=DP-2:1920x1080@60e rootflags=subvol=/@ root=UUID=238af85d

     //Snapshots
     ///74 │ 2026-10-19 13:29:24
     ////linux-cachyos
     cmdline: quiet splash rw rootflags=subvol=/@/.snapshots/74/snapshot root=UUID=238af85d

/+Other systems and bootloaders
//Windows Boot Manager
    protocol: efi_chainload
    image_path: guid():/efi/Microsoft/Boot/bootmgfw.efi
/EFI fallback
### This EFI entry is auto-generated by limine-entry-tool
comment: Default EFI loader
comment: order-priority=10 
protocol: efi
path: boot():/EFI/BOOT/BOOTX64.EFI"""

fails = []


def check(name, ok):
    print(("PASS " if ok else "FAIL ") + name)
    if not ok:
        fails.append(name)


new = lt.retheme(SAMPLE, "boot():/limine-ombu.jpg")
head, rest = lt.split(SAMPLE)
nhead, nrest = lt.split(new)
check("las entradas quedan idénticas", rest == nrest)
check("conserva el tiempo de espera y la entrada por defecto", "timeout: 5" in nhead and "default_entry: 2" in nhead and "remember_last_entry: yes" in nhead)
check("conserva term_background tal cual", "term_background: ffffffff" in nhead and "term_background_bright: ffffffff" in nhead)
check("cambia la paleta", "term_palette: 161011;e23b32" in nhead and "1e1e2e" not in nhead)
check("pone la marca", "interface_branding: OMBU" in nhead)
check("apunta al fondo nuevo", "wallpaper: boot():/limine-ombu.jpg" in nhead and "limine-splash" not in nhead)
check("agrega los colores que faltaban", "interface_branding_colour: e23b32" in nhead)
check("sigue estando Windows y el cargador de respaldo", "Windows Boot Manager" in nrest and "EFI fallback" in nrest)
check("correrlo dos veces da lo mismo", lt.retheme(new, "boot():/limine-ombu.jpg") == new)
try:
    lt.retheme("timeout: 5\n")
    check("sin entradas se niega a escribir", False)
except ValueError:
    check("sin entradas se niega a escribir", True)
alias = lt.retheme("interface_branding_color: 112233\n\n/Arch\n  protocol: linux\n")
check("un alias (color) se unifica sin duplicar", alias.count("interface_branding_colour") == 1 and "112233" not in alias)

# Arranque directo y sin Windows fantasma
d = lt.retheme(SAMPLE, "boot():/limine-ombu.jpg", direct=True, drop=True)
dhead, drest = lt.split(d)
check("directo: quiet y 2 segundos", "quiet: yes" in dhead and "timeout: 2" in dhead)
check("directo: arranca siempre la entrada por defecto", "remember_last_entry: no" in dhead and "default_entry: 2" in dhead)
check("saca Windows y el cargador de respaldo", "Windows" not in d and "EFI fallback" not in d and "Other systems" not in d)
check("conserva CachyOS y las instantáneas intactas", "/+CachyOS" in drest and "///74" in drest and "linux-cachyos" in drest)
check("el kernel (con sus hashes) queda igual", [l for l in rest.split("\n") if "module_path" in l or l.strip().startswith("path:")] == [l for l in drest.split("\n") if "module_path" in l or l.strip().startswith("path:")])
check("directo+sin Windows también es repetible", lt.retheme(d, "boot():/limine-ombu.jpg", direct=True, drop=True) == d)

print("\nTODO BIEN" if not fails else "\nFALLARON: " + ", ".join(fails))
sys.exit(1 if fails else 0)
